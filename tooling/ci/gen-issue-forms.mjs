#!/usr/bin/env node
// ─────────────────────────────────────────────────────────────────────────────
// gen-issue-forms.mjs — the extension dropdown of the two root issue forms,
// generated from every extension's tool.json.
//
// Row O-NEW-TOOL-IS-A-COPIER-NOT-THE-COMMAND. Until 2026-09-26 a bash step in
// extensions-ci.yml (discover job, "Issue templates list every tool id") grepped
// .github/ISSUE_TEMPLATE/bad-page.yml and bug.yml for "(<id>)" per tool, and
// new-tool.mjs told the author to type the option by hand because "issue forms
// cannot be generated". They can: each form carries ONE dropdown with a marked
// region, and this file writes the region.
//
//   --check [root]   exit 1 unless each form's region is exactly what the tool
//                    walk renders; names every id missing from a form.
//   --write [root]   rewrite each form's region in place.
//   --root <root>    the repository root (default: two directories up).
//
// THE TOOL WALK is the old step's `find`, moved here verbatim as data:
//   find . -mindepth 3 -maxdepth 3 -name tool.json \
//     -not -path './.git/*' -not -path './templates/*' \
//     -not -path './_skeleton/*' -not -path './private/*' \
//     -not -path './node_modules/*'
// run from extensions/, so a tool is extensions/<A>/<B>/tool.json.
//
// Exit codes: 0 green; 1 a finding; 2 COVERAGE LOST — a form is missing or has
// no region to write, or the walk found no tool at all. A dropdown graded
// against zero ids passes everything, which is the one answer it must never give.
// ─────────────────────────────────────────────────────────────────────────────
import { readFileSync, writeFileSync, statSync } from 'node:fs';
import { join, resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { listDir } from './tree-walk.mjs';

export const TOOL_TREE_REL = 'extensions';
export const FORMS_DIR_REL = '.github/ISSUE_TEMPLATE';

/** Each form, and how it words one extension's option. The wording is the form's
 *  own and predates this file; only the parenthesised id is graded. */
export const FORMS = [
  { rel: `${FORMS_DIR_REL}/bad-page.yml`, option: (t) => `${t.name} (${t.id})` },
  { rel: `${FORMS_DIR_REL}/bug.yml`, option: (t) => `${t.name} extension (${t.id})` },
];

export const BEGIN = '# BEGIN GENERATED by tooling/ci/gen-issue-forms.mjs --write from every extension tool.json. Never hand-edit between the markers.';
export const END = '# END GENERATED extension options';

/** The find's `-not -path './<dir>/*'` list, verbatim. */
const EXCLUDED_TOP = ['.git', 'templates', '_skeleton', 'private', 'node_modules'];

const isDir = (abs) => { try { return statSync(abs).isDirectory(); } catch { return false; } };
const isFile = (abs) => { try { return statSync(abs).isFile(); } catch { return false; } };

/**
 * Every extensions/<A>/<B>/tool.json the old `find` matched, sorted by path, as
 * `{ rel, id, name }` or `{ rel, error }` for one with no usable id.
 */
export function walkTools(root) {
  const tree = join(root, TOOL_TREE_REL);
  const out = [];
  if (!isDir(tree)) return out;
  for (const a of listDir(tree).sort()) {
    if (EXCLUDED_TOP.includes(a) || !isDir(join(tree, a))) continue;
    for (const b of listDir(join(tree, a)).sort()) {
      const abs = join(tree, a, b, 'tool.json');
      if (!isFile(abs)) continue;
      const rel = `${TOOL_TREE_REL}/${a}/${b}/tool.json`;
      let t = null;
      try { t = JSON.parse(readFileSync(abs, 'utf8').replace(/^\uFEFF/, '')); } catch { /* reported below */ }
      if (!t || typeof t.id !== 'string' || !t.id) {
        out.push({ rel, error: 'tool.json has no "id", or could not be parsed at all — the id is the stable public handle every tag, zip and matrix entry is built from.' });
        continue;
      }
      out.push({ rel, id: t.id, name: typeof t.name === 'string' && t.name.trim() ? t.name.trim() : t.id });
    }
  }
  return out;
}

/**
 * The form text with its marked region replaced by one option per tool, at the
 * indentation of the BEGIN marker. Returns `{ text }`, or `{ lost }` when the
 * form carries no single BEGIN…END pair.
 */
export function renderForm(text, tools, option) {
  const lines = text.split('\n');
  const b = lines.findIndex((l) => l.trim() === BEGIN);
  const e = lines.findIndex((l) => l.trim() === END);
  const count = (m) => lines.filter((l) => l.trim() === m).length;
  if (b === -1 || e === -1 || e < b || count(BEGIN) !== 1 || count(END) !== 1) {
    return { lost: 'carries no single BEGIN/END marker pair, so there is no region to generate' };
  }
  const indent = lines[b].match(/^ */)[0];
  const body = tools.map((t) => `${indent}- ${option(t)}`);
  return { text: [...lines.slice(0, b + 1), ...body, ...lines.slice(e)].join('\n') };
}

/** The ids whose `(<id>)` is absent from the form's region. */
export function missingIds(text, tools) {
  const lines = text.split('\n');
  const b = lines.findIndex((l) => l.trim() === BEGIN);
  const e = lines.findIndex((l) => l.trim() === END);
  const region = b !== -1 && e > b ? lines.slice(b + 1, e).join('\n') : '';
  return tools.filter((t) => !region.includes(`(${t.id})`)).map((t) => t.id);
}

function main(argv) {
  const flag = (name) => { const i = argv.indexOf(name); return i === -1 ? null : argv[i + 1] ?? ''; };
  const positional = argv.filter((a, i) => !a.startsWith('--') && argv[i - 1] !== '--root');
  const write = argv.includes('--write');
  const here = dirname(fileURLToPath(import.meta.url));
  const root = resolve(flag('--root') ?? positional[0] ?? join(here, '..', '..'));
  const lost = (m) => { console.error(`COVERAGE LOST — gen-issue-forms: ${m}`); process.exit(2); };

  const walked = walkTools(root);
  const bad = walked.filter((t) => t.error);
  const tools = walked.filter((t) => !t.error);
  for (const t of bad) console.error(`✗ ${t.rel}: ${t.error}`);
  if (walked.length === 0) lost(`no ${TOOL_TREE_REL}/<A>/<B>/tool.json under ${root}, so the dropdowns would be graded against zero ids.`);

  let fail = bad.length > 0;
  for (const f of FORMS) {
    const abs = join(root, f.rel);
    // Read, never exists-checked first: a check and then --write's write left a
    // window in which the file could change between the two (CodeQL
    // js/file-system-race). A path that names no file is COVERAGE LOST; any
    // other read error (a directory, say) is thrown, as it was.
    let text;
    try {
      text = readFileSync(abs, 'utf8');
    } catch (e) {
      if (e?.code === 'ENOENT' || e?.code === 'ENOTDIR') lost(`${f.rel} does not exist. This grades the issue forms a reporter actually sees, and a missing form must not read as a form with every id in it.`);
      throw e;
    }
    const r = renderForm(text, tools, f.option);
    if (r.lost) lost(`${f.rel} ${r.lost}.`);
    if (write) {
      if (r.text !== text) { writeFileSync(abs, r.text, 'utf8'); console.log(`wrote ${f.rel}: ${tools.map((t) => t.id).join(', ')}`); }
      else console.log(`unchanged ${f.rel}`);
      continue;
    }
    const missing = missingIds(text, tools);
    for (const id of missing) console.error(`✗ ${f.rel}: tool id '${id}' is missing from the extension dropdown — a reporter cannot name this tool. Run \`node tooling/ci/gen-issue-forms.mjs --write\` and commit what it writes.`);
    if (r.text !== text) {
      if (!missing.length) console.error(`✗ ${f.rel}: the generated region differs from what the tool.json files render. Run \`node tooling/ci/gen-issue-forms.mjs --write\` and commit what it writes.`);
      fail = true;
    }
  }
  // The old step's coverage line, printed rather than assumed.
  console.log(`issue-template dropdowns graded against ${tools.length} tool id(s), in ${join(root, FORMS_DIR_REL)}/.`);
  process.exit(fail ? 1 : 0);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main(process.argv.slice(2));
