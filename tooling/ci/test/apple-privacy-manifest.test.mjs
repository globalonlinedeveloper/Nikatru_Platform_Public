/**
 * 🔴 THE ONE SUBJECT FILE THAT IS NOT IN GIT, AND WHY IT NEEDS A FIXTURE.
 *
 * `apps/<app>/.flutter-plugins-dependencies` is GENERATED by `flutter pub get` and
 * IGNORED (apps/subscriptiontracker/.gitignore:30). It is the right thing for the GUARD to read —
 * it is what the Apple build actually links, so it is the only derivation of the
 * plugin set that cannot go stale — and the guard runs in `workspace_gate`, right
 * after `flutter pub get --enforce-lockfile`, where it exists.
 *
 * This TEST FILE is a different matter: ci.yml runs the whole `tooling/ci/test/*`
 * glob in the `platform` lane, which has no Flutter in it at all, so on a CI runner
 * the file is simply absent and every case here died on one assertion. That is not
 * a finding about the guard — it is this file depending on something git does not
 * carry.
 *
 * So: the REAL file is used whenever it exists (a developer machine, and preflight,
 * where the mutations therefore still range over the real tree exactly as intended),
 * and a committed fixture stands in when it does not.
 *
 * ⚠️ A FIXTURE THAT NOBODY COMPARES IS A FIXTURE THAT ROTS, and a stale one here
 * would make the plugin-set limb pass against a plugin list the build stopped
 * having. `the committed fixture still matches the real generated file` below is
 * that comparison; it runs wherever the real file exists and states plainly that it
 * cannot run on a Flutter-less runner.
 */
const PLUGIN_DEPS_REL = `apps/${APP}/.flutter-plugins-dependencies`;
const PLUGIN_DEPS_FIXTURE = join(CI_DIR, 'test', 'fixtures', 'subscriptiontracker.flutter-plugins-dependencies.json');
const realPluginDeps = () => join(REPO, PLUGIN_DEPS_REL);
const havePluginDeps = () => existsSync(realPluginDeps());
const pluginDepsSource = () => (havePluginDeps() ? realPluginDeps() : PLUGIN_DEPS_FIXTURE);

/** Everything the guard reads. Copied verbatim; the tests break one at a time. */
const SUBJECT_FILES = [
  ['pubspec.lock', 'pubspec.lock'],
  [`apps/${APP}/${AUDIT_REL}`, `apps/${APP}/${AUDIT_REL}`],
  [`apps/${APP}/store/android-play/data-safety.json`, `apps/${APP}/store/android-play/data-safety.json`],
  [`apps/${APP}/.flutter-plugins-dependencies`, `apps/${APP}/.flutter-plugins-dependencies`],
  ...PLATFORMS.map((p) => [`apps/${APP}/${MANIFEST_REL[p]}`, `apps/${APP}/${MANIFEST_REL[p]}`]),
  ...PLATFORMS.map((p) => [`apps/${APP}/${PBXPROJ_REL[p]}`, `apps/${APP}/${PBXPROJ_REL[p]}`]),
];

let TMP;
let seq = 0;
before(() => {
  TMP = mkdtempSync(join(tmpdir(), 'nikatru-appleprivacy-'));
});
after(() => {
  if (TMP) rmSync(TMP, { recursive: true, force: true });
});

const run = (root) => {
  const r = spawnSync(process.execPath, [GUARD, root], { encoding: 'utf8' });
  return { code: r.status, out: `${r.stdout}${r.stderr}` };
};

/** A copy of the real subject tree. `mutate(root)` breaks exactly one thing. */
function tree(mutate) {
  const root = join(TMP, `t${seq++}`);
  for (const [from, to] of SUBJECT_FILES) {
    const src = from === PLUGIN_DEPS_REL ? pluginDepsSource() : join(REPO, from);
    assert.ok(existsSync(src), `subject file missing from the real tree: ${from}`);
    const dst = join(root, to);
    mkdirSync(dirname(dst), { recursive: true });
    cpSync(src, dst);
  }
  if (mutate) mutate(root);
  return root;
}

const read = (root, rel) => readFileSync(join(root, rel), 'utf8');
const write = (root, rel, text) => writeFileSync(join(root, rel), text);

/** Replace, and REFUSE to continue if nothing changed. A no-op mutation is a
 *  broken test, not a weak guard, and the difference is invisible unless you go
 *  and look. */
function mutated(text, from, to, what) {
  const next = typeof from === 'string' ? text.replace(from, to) : text.replace(from, to);
  assert.notEqual(next, text, `mutation did not land: ${what}`);
  return next;
}

/** Edit the audit and REGENERATE both manifests, so limb 1 stays green and the
 *  limb under test is the only thing that can fire. Without this every audit
 *  mutation would trip the byte comparison first and prove nothing about the
 *  limb it was written for. */
function editAuditAndRegenerate(root, edit) {
  const rel = `apps/${APP}/${AUDIT_REL}`;
  const audit = JSON.parse(read(root, rel));
  const before = JSON.stringify(audit);
  edit(audit);
  assert.notEqual(JSON.stringify(audit), before, 'audit mutation did not land');
  write(root, rel, `${JSON.stringify(audit, null, 2)}\n`);
  const rendered = renderAll(audit, APP);
  for (const p of PLATFORMS) write(root, `apps/${APP}/${MANIFEST_REL[p]}`, rendered[p]);
}

