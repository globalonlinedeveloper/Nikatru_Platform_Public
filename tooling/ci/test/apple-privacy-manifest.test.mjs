describe('assert-apple-privacy-manifest.mjs — the positive controls', () => {
  // 🔴 THESE RUN AGAINST tree(null), NOT AGAINST REPO, AND THE REASON IS NOT
  // COSMETIC. The guard reads exactly SUBJECT_FILES, so an unmutated copy of them
  // IS the real subject — and on a machine that has run `flutter pub get`, tree()
  // copies the REAL .flutter-plugins-dependencies, so this is the real tree.
  // Pointed at REPO instead, all three died on a Flutter-less CI runner, where the
  // generated file does not exist: a positive control that cannot run in CI is a
  // positive control CI does not have. The stronger check against the literal
  // repository is kept below, conditioned on the file being there.
  test('the REAL repository passes', () => {
    const { code, out } = run(tree(null));
    assert.equal(code, 0, `the real tree must pass, got:\n${out}`);
  });

  test('an unmutated copy of the real subject files passes', () => {
    const { code, out } = run(tree(null));
    assert.equal(code, 0, `the baseline copy must pass, got:\n${out}`);
  });

  test('it PRINTS what it cannot see on every run, in the audit\'s own words', () => {
    const { code, out } = run(tree(null));
    assert.equal(code, 0);
    assert.match(out, /CANNOT SEE — THE COCOAPODS CLOSURE/);
    assert.match(out, /Sentry\/HybridSDK 8\.58\.4/);
    assert.match(out, /CANNOT SEE — THE BUILT BUNDLE/);
    assert.match(out, /UNRESOLVED U-1/);
    assert.match(out, /objc_msgSend/);

    // …and the words are READ from the audit, not restated in the guard: an item
    // that exists only in this copy of the audit must print. A guard carrying its
    // own text would print the sentences above and never this one
    // (O-UNGRADED-MECHANISM-CLAIMS, tooling/mechanism-claims.json).
    const planted = 'PLANTED ITEM THAT EXISTS ONLY IN THIS FIXTURE AUDIT';
    const t = tree((root) =>
      editAuditAndRegenerate(root, (audit) => {
        assert.ok(Array.isArray(audit.cannotSee?.items), 'the real audit carries cannotSee.items');
        audit.cannotSee.items.push(planted);
      }),
    );
    const edited = run(t);
    assert.equal(edited.code, 0, edited.out);
    assert.match(edited.out, new RegExp(`CANNOT SEE — ${planted}`));
  });

  test('it WARNS, and does not fail, on constants whose witness is `knowledge`', () => {
    const { code, out } = run(tree(null));
    assert.equal(code, 0);
    assert.match(out, /witness `knowledge`/);
    assert.match(out, /collectedDataType NSPrivacyCollectedDataTypeCoarseLocation/);
  });

  // The literal working tree, in place, with nothing copied — the one check that
  // proves the guard is green on the repository a human is actually holding. It
  // needs the generated plugin file, so it states plainly when it could not run
  // rather than reporting ok over a thing it did not do.
  test('the literal working tree passes, where the generated plugin file exists', (t) => {
    if (!havePluginDeps()) {
      t.diagnostic(
        `no ${PLUGIN_DEPS_REL} on this machine (generated, gitignored), so the guard was not run ` +
          'against the working tree in place. The copy-based controls above still ran.',
      );
      return;
    }
    const { code, out } = run(REPO);
    assert.equal(code, 0, `the literal working tree must pass, got:\n${out}`);
  });
});

