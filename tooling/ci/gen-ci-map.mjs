#!/usr/bin/env node
// ─────────────────────────────────────────────────────────────────────────────
// gen-ci-map.mjs — the CI docs' workflow facts, written from the workflows.
//
// Rows O-CI-DOCS-DESCRIBE-A-GONE-TREE and O-GUARD-HEADERS-CITE-CODE-BY-LINE-NUMBER
// (limb c). Until this file, docs/ci/README.md §3, §6, §7 and §9 and
// tooling/release/RELEASE-RUNBOOK.md §2 each carried a hand copy of a fact the
// workflows already state, and each copy had moved away from its source: the
// runbook named the tag lane by a `name:` the workflow no longer has and said
// one workflow triggers on a tag where two do; §7 counted five third-party
// actions where the tree uses six; §6 named a Windows secret no workflow reads.
// Nothing compared any of them to the files.
//
// Five marker blocks, each rendered from tooling/ci/workflow-scan.mjs (the one
// workflow reader) and nothing else:
//
//   docs/ci/README.md                  lane-map   ci.yml's jobs and ci-gate's needs (§3)
//                                      secrets    every `secrets.NAME` a workflow reads (§6)
//                                      actions    every action a workflow or a composite
//                                                 action under .github/actions uses (§7)
//                                      workflows  one row per workflow, with its page (§9)
//   tooling/release/RELEASE-RUNBOOK.md tag-trigger every workflow with `on: push: tags:` (§2)
//
// A block is the lines between
//   <!-- BEGIN GENERATED: gen-ci-map <block> -->
//   <!-- END GENERATED: gen-ci-map <block> -->
// and its first line is the `<!-- why: GENERATED by … --write. Never hand-edit. -->`
// comment. --write replaces what is between the two markers and nothing else.
//
// --check also runs three limbs over the lane pages and the tree:
//   (a) every `### above \`X\`` heading in docs/ci/<w>.md quotes X, and X is on
//       a line of .github/workflows/<w>.yml. A page's anchor that names a line
//       the workflow no longer has points a reader at nothing. An X ending in
//       `…` is the start of a long line, and only that start is looked for.
//   (b) a `##` heading in a lane page that names ONE token — `## job \`X\`` or a
//       lone `## X` — names a job of that workflow. The 2026-09-06 migration
//       wrote a `## job` heading for some keys inside a job (`strategy`, `with`,
//       `needs`, `permissions`), and a reader then looks for a job that is not
//       there. Such a heading is demoted to `###`.
//   ⏱ 2026-09-26 (option B): for (a) and (b), "its workflow" is the page's
//       workflow AND every workflow it calls by a local `uses:`, as workflow-scan's
//       resolveLocalCalls reads them; a call that does not resolve is COVERAGE LOST.
//       docs/ci/extensions.md documents extensions-ci.yml's jobs, which
//       extensions.yml's `ci` job calls.
//   (c) no git-tracked file outside docs/ cites a line of a docs/ci page or of
//       RELEASE-RUNBOOK.md by number: every edit above the cited line moves it,
//       and most moved citations land on another real line. Cite the section
//       heading or the job instead. The files come from `git ls-files`, never a
//       filesystem walk, so an untracked scratch file is not the tree.
//
// Usage:
//   node tooling/ci/gen-ci-map.mjs [--check] [root]   (the default mode)
//   node tooling/ci/gen-ci-map.mjs --write [root]
//
// Exit codes: 0 green; 1 a finding, each printed as `file:line — what — the fix`;
// 2 COVERAGE LOST — a marker missing or doubled, a workflow that parses to no
// job, no workflow at all, no lane page in docs/ci, or a `git ls-files` that
// listed nothing. A block rendered from an empty tree, or a limb that read no
// file, would pass.
// ─────────────────────────────────────────────────────────────────────────────
