#!/usr/bin/env node
// ─────────────────────────────────────────────────────────────────────────────
// generate-apps-data.mjs — the site's Eleventy data file, generated from the
// published catalogue.
//
//     catalog/apps.json  ──(this script)──▶  sites/_shared/_data/apps.json
//
// The output is COMMITTED and CI re-runs this script and DIFFS, exactly as
// `generate-discovery.mjs` does for the discovery surface, and for the same
// reason: `sites/_shared` is consumed by Eleventy and by a build-time TypeScript
// import in `services/platform/src/config.ts`. A generator whose output only
// exists inside a CI job produces bytes nobody serves.
//
// ── WHY THE SITE FILE STAYS EXACTLY WHERE IT IS ──────────────────────────────
// `sites/_shared/eleventy.config.js` sets `dir.data = "_data"`, and Eleventy
// derives the global template variable FROM THE FILENAME: `_data/apps.json`
// becomes `{{ apps }}`. `demo/index.njk` and `_includes/partials/app-card.njk`
// iterate `{% for app in apps %}` and NEVER name the file. Move or rename it and
// the variable silently becomes undefined, the loop renders zero cards, and
// nothing errors and no guard fires. So the file keeps its exact path and its
// exact shape; only its PROVENANCE changes — it stops being hand-written and
// becomes a derived artifact.
//
// ── WHY THIS IS A FORMATTER AND NOT A `cp` ───────────────────────────────────
// A byte copy was the obvious implementation and it is the wrong one, for a
// reason that is measurable rather than aesthetic.
//
// The committed file is HAND-FORMATTED: `"platforms": ["web"]` sits inline on
// one line. `JSON.stringify(parsed, null, 2) + '\n'` expands that array to three
// lines and yields 247 bytes where 235 stand (re-measured 2026-08-17), and Dart's
// `JsonEncoder.withIndent('  ')` — which `tooling/bricks/app/hooks/post_gen.dart`
// uses — expands it identically. post_gen REWRITES THE WHOLE FILE on every stamp.
// So under a byte copy, the first app stamped after the inversion reformats every
// pre-existing row of the live site's data file as a side effect of adding an
// unrelated app. Under this formatter, the catalogue may be written by Dart, by
// jq, or by hand in any of those shapes and the site file's bytes stay a function
// of its CONTENT alone.
//
// That is also what makes the drift check meaningful, which is the property the
// tokens lane's header calls out: no timestamps, no environment, no dependence
// on which tool last touched the source. Same input, same bytes, forever.
//
// ── WHAT IT DELIBERATELY DOES NOT DO: PROJECT ────────────────────────────────
// Every field in a catalogue row is passed through. It is tempting to emit only
// the fields the site renders (`app-card.njk` uses slug/name/tagline/url/
// platforms/status — `api` is read by nothing on the site, only by
// `services/platform/src/config.ts` and `assert-cors-allowlist.mjs`), but
// dropping the rest would be a BEHAVIOUR CHANGE, not a mechanism change:
// post_gen writes `markets` and `audience` into every row it stamps, straight
// into this file, today. A projection would silently delete data that currently
// reaches this path — and "silently stops carrying what it used to" is the
// failure shape this repo pays for most often. If the site should publish fewer
// fields than the catalogue holds, that is a decision with its own record, not a
// side effect of moving the file.
//
// A new catalogue field therefore CHANGES THE GENERATED BYTES, so `--check` goes
// red until a human regenerates and commits. That is the protection. The notice
// this script prints is a convenience; the red check is the enforcement.
//
// ── THE OUTPUT CANNOT CARRY A "GENERATED, DO NOT EDIT" HEADER ────────────────
// JSON has no comment syntax, and this file's top level is an ARRAY, so there is
// not even a stray key to hang the notice on. Any marker at all would change the
// bytes — which is precisely what this increment forbids. So the drift check IS
// the only protection against a hand edit to `sites/_shared/_data/apps.json`:
// nothing in the file itself tells an editor to stop.
//
// Usage:  node tooling/sites/generate-apps-data.mjs [root] [--check]
//         (default) writes the file if its bytes differ
//         --check   renders in memory and DIFFS; exit 1 on drift, writes nothing
// ─────────────────────────────────────────────────────────────────────────────

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const CATALOGUE = 'catalog/apps.json';
export const SITE_DATA = 'sites/_shared/_data/apps.json';

/**
 * Canonical field order for the fields the catalogue is known to carry.
 *
 * Locked so that the output depends on the row's CONTENT and not on the key
 * order whichever tool last wrote the catalogue happened to emit. Fields absent
 * from a row are skipped; fields NOT listed here are emitted after these, sorted
 * by name, so an unrecognised field is carried through deterministically rather
 * than dropped (see the header).
 */
const FIELD_ORDER = ['slug', 'name', 'tagline', 'url', 'api', 'platforms', 'status'];

/* ------------------------------------------------------------------ */
/* Serialisation                                                      */

/**
 * Emit JSON in THIS repo's hand-written house style, which no standard encoder
 * reproduces: 2-space indent, but an array whose elements are all non-objects
 * stays on one line as `[a, b]`.
 *
 * ⚠️ The inline case builds the list with `.map(JSON.stringify).join(', ')` and
 * NOT `JSON.stringify(v).replace(/,/g, ', ')`. The replace form corrupts any
 * string containing a comma (`["a,b"]` -> `["a, b"]`) and — this is the trap —
 * the two forms produce IDENTICAL bytes on today's data, so a test against the
 * current catalogue cannot tell them apart. Verified by direct probe.
 */
function serialise(value, indent = '') {
  if (Array.isArray(value)) {
    if (value.length === 0) return '[]';
    if (value.every((el) => el === null || typeof el !== 'object')) {
      return `[${value.map((el) => JSON.stringify(el)).join(', ')}]`;
    }
    const inner = value.map((el) => `${indent}  ${serialise(el, `${indent}  `)}`).join(',\n');
    return `[\n${inner}\n${indent}]`;
  }
  if (value && typeof value === 'object') {
    const keys = Object.keys(value);
    if (keys.length === 0) return '{}';
    const inner = keys
      .map((k) => `${indent}  ${JSON.stringify(k)}: ${serialise(value[k], `${indent}  `)}`)
      .join(',\n');
    return `{\n${inner}\n${indent}}`;
  }
  return JSON.stringify(value);
}

/** Re-key one row into FIELD_ORDER, then any remaining fields sorted by name. */
function orderRow(row) {
  const out = {};
  for (const field of FIELD_ORDER) {
    if (Object.prototype.hasOwnProperty.call(row, field)) out[field] = row[field];
  }
  for (const key of Object.keys(row).sort()) {
    if (!Object.prototype.hasOwnProperty.call(out, key)) out[key] = row[key];
  }
  return out;
}

/* ------------------------------------------------------------------ */
/* Plan                                                               */

/**
 * Read the catalogue and render the site data file. Returns
 * `{ contents, rows, extraFields, problems }`; `contents` is null when
 * `problems` is non-empty.
 *
 * Refusals are deliberate and each one is reachable:
 *   · catalogue absent            — the whole feed would silently vanish
 *   · not an array / not objects  — Eleventy would render nothing, no error
 *   · ZERO rows                   — see below
 *   · a row with no string `slug` — `generate-discovery.mjs` keys pages on slug
 *   · duplicate slugs             — two cards, one URL, last write wins
 *
 * 🔴 ZERO ROWS IS AN ERROR, NOT AN EMPTY RESULT. A generator that happily writes
 * `[]` turns "the catalogue got truncated" into "the live site lists no apps",
 * with a green build. There is no legitimate path that reaches this script with
 * an empty catalogue, so refusing is both correct and what makes this script a
 * well-behaved subject for `assert-guards-refuse-empty.mjs`.
 */
export function planAppsData(root) {
  const problems = [];
  const cataloguePath = join(root, ...CATALOGUE.split('/'));

  if (!existsSync(cataloguePath)) {
    problems.push(
      `${CATALOGUE} does not exist. It is the published catalogue this file is generated from ` +
        `(written by tooling/bricks/app/hooks/post_gen.dart when an app is stamped). ` +
        `Without it there is nothing to generate ${SITE_DATA} from, and refusing is the only ` +
        `safe answer — writing an empty feed would empty the live site.`,
    );
    return { contents: null, rows: [], extraFields: [], problems };
  }

  const raw = readFileSync(cataloguePath, 'utf8');
  let parsed;
  try {
    parsed = JSON.parse(raw);
  } catch (err) {
    problems.push(`${CATALOGUE} is not valid JSON: ${err.message}`);
    return { contents: null, rows: [], extraFields: [], problems };
  }

  if (!Array.isArray(parsed)) {
    problems.push(`${CATALOGUE} must be a JSON array of app rows; found ${typeof parsed}.`);
    return { contents: null, rows: [], extraFields: [], problems };
  }
  if (parsed.length === 0) {
    problems.push(
      `${CATALOGUE} contains zero rows. Refusing to write an empty ${SITE_DATA}: the site would ` +
        `list no apps and nothing would fail.`,
    );
    return { contents: null, rows: [], extraFields: [], problems };
  }

  const seen = new Set();
  parsed.forEach((row, i) => {
    if (row === null || typeof row !== 'object' || Array.isArray(row)) {
      problems.push(`${CATALOGUE}[${i}] is not an object.`);
      return;
    }
    if (typeof row.slug !== 'string' || row.slug.trim() === '') {
      problems.push(`${CATALOGUE}[${i}] has no non-empty string "slug".`);
      return;
    }
    if (seen.has(row.slug)) problems.push(`${CATALOGUE} lists slug "${row.slug}" more than once.`);
    seen.add(row.slug);
  });
  if (problems.length) return { contents: null, rows: parsed, extraFields: [], problems };

  const extraFields = [
    ...new Set(parsed.flatMap((row) => Object.keys(row).filter((k) => !FIELD_ORDER.includes(k)))),
  ].sort();

  const contents = `${serialise(parsed.map(orderRow))}\n`;
  return { contents, rows: parsed, extraFields, problems };
}

/* ------------------------------------------------------------------ */
/* CLI                                                                */

const isMain = process.argv[1] && resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url));
if (isMain) {
  const argv = process.argv.slice(2);
  const check = argv.includes('--check');
  const positional = argv.find((a) => !a.startsWith('--'));
  const root = resolve(positional ?? join(dirname(fileURLToPath(import.meta.url)), '..', '..'));

  const { contents, rows, extraFields, problems } = planAppsData(root);
  if (problems.length) {
    console.error(`✗ ${problems.length} problem(s) reading the catalogue:`);
    for (const p of problems) console.error(`    ${p}`);
    process.exit(1);
  }

  const target = join(root, ...SITE_DATA.split('/'));
  const current = existsSync(target) ? readFileSync(target, 'utf8') : null;

  if (extraFields.length) {
    console.log(
      `    note ${CATALOGUE} carries field(s) this script does not order explicitly and passes ` +
        `through: ${extraFields.join(', ')}`,
    );
  }

  if (check) {
    if (current === contents) {
      console.log(`ok  ${SITE_DATA} matches ${CATALOGUE} — ${rows.length} row(s), ${Buffer.byteLength(contents)} bytes`);
      process.exit(0);
    }
    console.error(`✗ ${SITE_DATA} has DRIFTED from ${CATALOGUE}.`);
    if (current === null) {
      console.error(`    the file does not exist; this script produces it. Run without --check.`);
    } else {
      console.error(
        `    committed: ${Buffer.byteLength(current)} bytes · regenerated: ${Buffer.byteLength(contents)} bytes`,
      );
      const a = current.split('\n');
      const b = contents.split('\n');
      for (let i = 0; i < Math.max(a.length, b.length); i++) {
        if (a[i] !== b[i]) {
          console.error(`    first difference at line ${i + 1}:`);
          console.error(`      committed:   ${a[i] === undefined ? '<end of file>' : JSON.stringify(a[i])}`);
          console.error(`      regenerated: ${b[i] === undefined ? '<end of file>' : JSON.stringify(b[i])}`);
          break;
        }
      }
    }
    console.error(`    ${SITE_DATA} is GENERATED. Do not hand-edit it — edit ${CATALOGUE} and re-run:`);
    console.error(`      node tooling/sites/generate-apps-data.mjs`);
    process.exit(1);
  }

  if (current === contents) {
    console.log(`ok  ${SITE_DATA} already current — ${rows.length} row(s), ${Buffer.byteLength(contents)} bytes`);
  } else {
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, contents);
    console.log(`    wrote ${SITE_DATA} — ${rows.length} row(s), ${Buffer.byteLength(contents)} bytes`);
  }
}
