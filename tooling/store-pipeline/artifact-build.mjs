/** Every artifact format the register names, derived from the register itself so
 *  the comparison in assert-slot-pipeline.mjs is against the real set and never
 *  against a second list. */
export function registerFormats(register) {
  const set = new Set();
  for (const ch of register.channels ?? []) for (const f of ch.artifactFormats ?? []) set.add(f);
  return set;
}
