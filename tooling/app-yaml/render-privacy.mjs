// 🔴 THE PAGE CARRIES THE SITE'S SHARED CHROME, IT DOES NOT OPT OUT OF IT.
// `chrome.mjs`'s `isChromePage` is DERIVED FROM THE TREE: a page added to
// sites/nikatru/ is in the chrome contract the moment it exists, and the only
// way out is a NAMED entry in CHROME_EXCLUDED with a written reason. The
// FullShot policy has one — it is a mirrored legal document whose footer is the
// publisher identification a store reviewer reads. This page is not mirrored and
// not a contract copy, so taking that exit would have been buying a green run
// with an exemption. It emits the four sentinel regions instead, which is also
// the only way it gets a skip link and a visible focus ring: C-WCAG-22-AA is a
// PUBLISHED claim, and a new page without them fails SC 2.4.1 and SC 2.4.7 on
// the day it ships.
