/**
 * Read every privacy declaration and compute every notice rendering. Nothing is
 * written here.
 *
 * 🔴 THE COVERAGE REFUSALS, AND WHY EACH IS 2 RATHER THAN 0. Every one of them
 * describes a run that rendered NOTHING and would otherwise print ok:
 *   · no apps/ directory                — there is no app to render a notice for
 *   · not one apps/<id>/privacy.yaml    — the declaration this renders from does
 *                                         not exist, so "0 renderings, all fresh"
 *   · not one extension STORE-LISTING.md
 *     carries the markers               — the store half rendered nothing, and
 *                                         the page alone is not what this is for
 *   · every extension listing is the
 *     template                          — the only thing rendered was the
 *                                         "no declaration yet" notice, which
 *                                         proves nothing about a real tool
 */
export function planPrivacy(root) {
  const problems = [];
  const lost = [];
  const files = new Map();
  const declarations = [];

  const schema = JSON.parse(readFileSync(PRIVACY_SCHEMA_PATH, 'utf8'));

  /** Parse and grade one declaration whose bytes have ALREADY been read. Taking
   *  the text rather than the path is what keeps this side of the script free of
   *  a check-then-read pair — see `readIf`. */
  const gradeDoc = (rel, text) => {
    let doc;
    try {
      doc = parseYaml(text);
    } catch (e) {
      problems.push(`${rel}: ${e instanceof YamlError ? e.message : String(e)}`);
      return null;
    }
    const bad = validate(doc, schema, rel);
    if (bad.length) {
      for (const b of bad) problems.push(b);
      return null;
    }
    // ⏱ 2026-09-24 — A REPOSITORY-PATH `source` MUST NAME A FILE THAT EXISTS.
    // The schema grades a source's SHAPE (repo-path or https-url) and nothing
    // opened it, so a row could cite a deleted file and still render and pass:
    // a source naming any missing path exited 0 here and in assert-app-yaml,
    // measured before this limb. A basis read from a file that is gone cannot be
    // re-read. An https source is an external authority and is not fetched. The
    // doc is still returned, so the run stays a FINDING (1) and never turns into
    // a coverage loss (2) for want of a declaration to render.
    const sources = [
      ...(doc.collects ?? []).map((r) => r?.source),
      ...(doc.storeDisclosures ?? []).map((r) => r?.source),
      ...(doc.processors ?? []).map((r) => r?.source),
      doc.limitedUse?.source,
    ].filter((s) => typeof s === 'string' && !s.startsWith('https://'));
    for (const s of [...new Set(sources)]) {
      if (!existsSync(join(root, s))) {
        problems.push(`${rel}: source ${s} does not exist in this repository. A row's basis must be re-readable from the file it names; point the source at the file that holds that reasoning now.`);
      }
    }
    return doc;
  };

  // ── the app notices ───────────────────────────────────────────────────────
  const appsAbs = join(root, APPS_DIR);
  if (!isDir(appsAbs)) {
    lost.push(`${APPS_DIR}/ does not exist, so this run had no app declaration to render a notice from.`);
    return { declarations, files, problems, lost };
  }
  // Read once. `readIf` returns null for an absent file, so the set of apps that
  // declare and the bytes they declare come out of the same observation.
  const appDeclarations = listDirs(appsAbs)
    .sort()
    .map((id) => [id, readIf(join(appsAbs, id, 'privacy.yaml'))])
    .filter(([, text]) => text !== null);
  if (appDeclarations.length === 0) {
    lost.push(
      `no ${APPS_DIR}/<id>/privacy.yaml exists. The per-app notice is a function of that declaration, so `
        + 'zero declarations render zero bytes and every comparison below would pass over an empty set.',
    );
    return { declarations, files, problems, lost };
  }
  // The company name printed for each processor. Read here, once, for every app.
  const registerText = readIf(join(root, PROVIDER_REGISTER));
  if (registerText === null) {
    lost.push(`${PROVIDER_REGISTER} does not exist, so no processor on an app notice can be named.`);
    return { declarations, files, problems, lost };
  }
  let providerNames;
  try {
    const reg = JSON.parse(registerText);
    providerNames = new Map(
      (Array.isArray(reg.providers) ? reg.providers : [])
        .filter((row) => row && typeof row.id === 'string' && typeof row.name === 'string')
        .map((row) => [row.id, row.name]),
    );
  } catch (e) {
    problems.push(`${PROVIDER_REGISTER}: not valid JSON (${e.message}), so no processor on an app notice can be named.`);
    return { declarations, files, problems, lost };
  }
  for (const [id, text] of appDeclarations) {
    const rel = `${APPS_DIR}/${id}/privacy.yaml`;
    const doc = gradeDoc(rel, text);
    if (!doc) continue;
    if (doc.app !== id) {
      problems.push(`${rel}: declares app "${doc.app}" but lives in ${APPS_DIR}/${id}/ — two files describing two different apps.`);
      continue;
    }
    if (doc.surface !== 'app') {
      problems.push(`${rel}: declares surface "${doc.surface}". A declaration under ${APPS_DIR}/ is the app surface; the extension surface lives under ${EXTENSIONS_DIR}/.`);
      continue;
    }
    // The display name comes from app.yaml when there is one — one name, one
    // source. Without it the id is used rather than a name being invented.
    let appName = id;
    const appYaml = readIf(join(root, APPS_DIR, id, 'app.yaml'));
    if (appYaml) {
      const m = /^name:\s*(.+)$/m.exec(appYaml);
      if (m) appName = m[1].trim().replace(/^["']|["']$/g, '');
    }
    let page;
    try {
      page = renderAppPage(doc, { appName, appId: id, providerNames });
    } catch (e) {
      problems.push(`${rel}: ${e.message}`);
      continue;
    }
    declarations.push({ surface: 'app', id, rel, doc });
    files.set(`${SITE_ROOT}/${id}/privacy.html`, page);
  }

  // ── the extension store blocks ────────────────────────────────────────────
  let listingsFenced = 0;
  let realListings = 0;
  const extAbs = join(root, EXTENSIONS_DIR);
  if (isDir(extAbs)) {
    for (const listingRel of findStoreListings(root)) {
      const current = readIf(join(root, listingRel));
      if (current === null) continue;
      if (!current.includes(MARK_START)) continue;
      listingsFenced += 1;
      const isTemplate = listingRel === TEMPLATE_LISTING;
      const declRel = `${dirname(listingRel)}/privacy.yaml`;
      let block;
      const declText = readIf(join(root, declRel));
      if (declText !== null) {
        // 🔴 COUNTED BEFORE IT IS VALIDATED, and that ordering is the whole
        // point. Counting a real tool's listing only once its declaration
        // PARSED means a broken declaration empties the count, the refusal
        // below fires, and the run exits 2 reporting "nothing to compare" —
        // hiding the finding, which is the broken declaration, behind a
        // coverage message that names the wrong repair. The guard's own limb 1
        // carries this exact correction in its header ("a declaration that does
        // not parse stops the run here… the finding is the broken declaration")
        // and it was re-learned here: `tooling/ci/test/app-yaml.test.mjs`'s
        // extension-grading case went 2 instead of 1 until this moved.
        if (!isTemplate) realListings += 1;
        const doc = gradeDoc(declRel, declText);
        if (!doc) continue;
        if (doc.surface !== 'extension') {
          problems.push(`${declRel}: declares surface "${doc.surface}". A declaration beside a store listing is the extension surface.`);
          continue;
        }
        declarations.push({ surface: 'extension', id: doc.app, rel: declRel, doc });
        block = renderStoreBlock(doc);
      } else {
        block = UNANSWERED;
      }
      const next = spliceBlock(current, block);
      if (next === null) {
        problems.push(`${listingRel}: carries the opening privacy-practices marker but not the closing one, so the fenced region has no end.`);
        continue;
      }
      files.set(listingRel, next);
    }
  }
  if (listingsFenced === 0) {
    lost.push(
      `not one ${EXTENSIONS_DIR}/**/publish/STORE-LISTING.md carries the privacy-practices markers. The store `
        + 'half of this renderer then covers nothing, and the per-app page alone is not what a privacy generator is for.',
    );
  } else if (realListings === 0) {
    lost.push(
      `every fenced store listing is the tool TEMPLATE — ${listingsFenced} fenced, 0 belonging to a real tool with a `
        + 'declaration. The only thing rendered was the "no declaration yet" notice, which proves nothing about any '
        + 'answer that reaches a store console.',
    );
  }

  return { declarations, files, problems, lost };
}

/** Every `publish/STORE-LISTING.md` under `extensions/`, repo-relative. */
function findStoreListings(root) {
  const out = [];
  const walk = (relDir) => {
    const abs = join(root, relDir);
    let entries;
    try {
      entries = readdirSync(abs, { withFileTypes: true });
    } catch {
      return;
    }
    for (const e of entries) {
      const rel = `${relDir}/${e.name}`;
      if (e.isDirectory()) {
        if (e.name === 'node_modules' || e.name === '.git') continue;
        walk(rel);
      } else if (e.name === 'STORE-LISTING.md' && relDir.endsWith('/publish')) {
        out.push(rel);
      }
    }
  };
  walk(EXTENSIONS_DIR);
  return out.sort();
}

/* ------------------------------------------------------------------ */
/* Main                                                                */

export function renderPrivacy(root, { check = false } = {}) {
  const { files, problems, lost, declarations } = planPrivacy(root);
  if (lost.length) return { code: 2, lost, problems, stale: [], wrote: [], total: 0, declarations };
  if (problems.length) return { code: 1, lost, problems, stale: [], wrote: [], total: 0, declarations };
  const stale = [];
  const wrote = [];
  for (const [rel, contents] of files) {
    const abs = join(root, rel);
    const current = readIf(abs);
    if (current === contents) continue;
    stale.push(rel);
    if (!check) {
      mkdirSync(dirname(abs), { recursive: true });
      writeFileSync(abs, contents);
      wrote.push(rel);
    }
  }
  return { code: check && stale.length ? 1 : 0, lost, problems, stale, wrote, total: files.size, declarations };
}

const invokedDirectly = process.argv[1] && resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url));
if (invokedDirectly) {
  const args = process.argv.slice(2);
  const check = args.includes('--check');
  const positional = args.filter((a) => !a.startsWith('--'));
  const root = resolve(positional[0] ?? join(HERE, '..', '..'));
  const r = renderPrivacy(root, { check });
  if (r.code === 2) {
    console.error('');
    for (const l of r.lost) console.error(`FAIL COVERAGE LOST — ${l}`);
    console.error('\nrender-privacy: COVERAGE LOST');
    process.exit(2);
  }
  if (r.problems.length) {
    for (const p of r.problems) console.error(`✗ ${p}`);
    console.error(`\nrender-privacy: ${r.problems.length} problem(s) in the declaration(s) — nothing was written.`);
    process.exit(1);
  }
  const apps = r.declarations.filter((d) => d.surface === 'app').length;
  const exts = r.declarations.filter((d) => d.surface === 'extension').length;
  if (check) {
    if (r.stale.length) {
      console.error('✗ these notice surfaces no longer match the declaration they are rendered from:');
      for (const s of r.stale) console.error(`    ${s}`);
      console.error('\n  Change the declaration, not the rendering, then:  node tooling/app-yaml/render-privacy.mjs');
      console.error('  (A STORE-LISTING.md edit BETWEEN the privacy-practices markers is exactly this failure.)');
      process.exit(1);
    }
    console.log(`ok   render-privacy --check — ${r.total} notice rendering(s) match ${apps} app and ${exts} extension declaration(s)`);
    process.exit(0);
  }
  if (r.wrote.length) for (const w of r.wrote) console.log(`wrote ${w}`);
  console.log(`ok   render-privacy — ${r.total} notice rendering(s) from ${apps} app and ${exts} extension declaration(s), ${r.wrote.length} rewritten`);
  process.exit(0);
}
