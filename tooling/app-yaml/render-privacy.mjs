/** HTML text. Every string below comes from a declaration a human wrote, so it
 *  is escaped rather than trusted — the same reason
 *  `render-fullshot-privacy.mjs` REFUSES inline HTML it does not recognise. */
export const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

/** A Markdown table cell. A literal pipe would end the cell and silently move
 *  every column after it one place left — a rendering that is wrong and looks
 *  deliberate. The numeric reference renders as the character it replaces. */
export const cell = (s) => String(s).replace(/\|/g, '&#124;').replace(/\r?\n/g, ' ').trim();

