#!/usr/bin/env node
// ─────────────────────────────────────────────────────────────────────────────
// render-privacy.mjs — the privacy DECLARATION is the source; the notice
// surfaces are RENDERINGS.
//
//   apps/<id>/privacy.yaml ─────(this script)──▶ sites/nikatru/<id>/privacy.html
//                                                (the per-app notice, incl. the
//                                                 itemised DPDP notice block)
//
//   extensions/<Cat>/<Tool>/publish/privacy.yaml ─▶ the Chrome Web Store
//                                                   privacy-practices block
//                                                   between the two markers in
//                                                   the sibling STORE-LISTING.md
//
// ── WHY A GENERATOR AT ALL, WHEN THE DECLARATION ALREADY EXISTS ──────────────
// `apps/subscriptiontracker/privacy.yaml`'s own header says what it was missing: "Its
// renderings — the Play data-safety answers, the Apple privacy manifest, the
// published policy text — are NOT generated from it today, and nothing here
// pretends they are." Two of those three must never be generated ([ADR 037] —
// a sworn declaration regenerated by a template is a statement nobody made).
// The third — the NOTICE a reader is shown — is exactly the thing that should
// be, because the alternative is a human retyping eleven categories, four
// processors and three retention classes into HTML and into a store console and
// nothing anywhere being able to tell the two apart from agreement.
//
// ── WHAT IT DELIBERATELY DOES NOT WRITE ──────────────────────────────────────
// ⛔ The four SWORN declarations under `apps/<id>/store/` — data-safety.json,
//    content-rating.json, ads-declaration.json, privacy-manifest.json. This
//    script never opens them. `assert-app-yaml.mjs` limb 4 READS two of them, in
//    the only direction that is safe: to check that the declaration and the
//    sworn answers still describe the same eleven rows.
// ⛔ `sites/nikatru/privacy.html`, the PORTFOLIO policy. It is pinned by
//    `kPrivacyPolicyVersion` in two Dart files, archived under
//    `sites/nikatru/legal/<version>/<locale>/`, and consent records cite its
//    version. A generator writing it would move a document people have already
//    agreed to. The per-app page below is a NOTICE ABOUT ONE APP that links to
//    it; it carries no `data-policy-version` of its own, on purpose, because
//    that attribute is the portfolio policy's identity and
//    `assert-policy-archive.mjs`'s VERSION_SOURCES is the closed list of files
//    allowed to declare one.
// ⛔ `app.yaml`'s `legal.privacyPolicyUrl`, from which the store
//    `privacy-policy-url.txt` files are rendered. A per-app privacy URL change
//    is a STORE LISTING change and is made deliberately and recorded, never as
//    a side effect of adding a page.
//
// ── THE PAGE IS NOT CONTRACT-SOURCED, AND THAT IS A MEASURED CHOICE ──────────
// 🔴 `assert-legal-text-parity.mjs` sweeps `contracts/legal/*.md` and FAILS any
// document there that is not published in at least TWO places
// (`MIN_COPIES_PER_DOCUMENT = 2`). The per-app notice is published in exactly
// ONE place. Putting its text under `contracts/legal/` would therefore fail that
// guard on the day it landed — and the repair would be either to weaken the
// floor or to invent a second copy. So the page is rendered from the
// declaration, its facts have one source, and `contracts/legal/` is untouched.
//
// ── `--check` IS THE ONLY THING BETWEEN A HAND EDIT AND A STORE CONSOLE ──────
// The HTML page carries a GENERATED / DO NOT EDIT header. The STORE-LISTING
// block cannot carry one of its own at the top of the file — the document is
// hand-written prose that a human maintains — so it is fenced by two markers
// and only the bytes BETWEEN them are rendered. Everything outside them is
// carried through unchanged, which is what makes an edit inside them detectable
// at all: the rendering of that file is "the file as it is, with the fenced
// region replaced".
//
// ⚠️ THE STYLE BLOCK'S VALUES ARE GENERATED TOKENS. `assert-palette-consistent.
// mjs` reads every page on the site and caught the imported FullShot policy's
// own greys as the only dissenting declaration on the whole site (that page's
// `:22-27` comment records it). The values below are the ones from
// `sites/_shared/assets/tokens.css` — edit `contracts/tokens`, never this file.
//
// Usage:  node tooling/app-yaml/render-privacy.mjs [root] [--check]
//         (default) writes every rendering whose bytes differ
//         --check   renders in memory and DIFFS; exit 1 NAMING each stale file
// Exit 0 = the notice surfaces match the declarations. 1 = they do not (or a
// declaration is invalid). 2 = COVERAGE LOST — see the refusals in `planPrivacy`.
// ─────────────────────────────────────────────────────────────────────────────
