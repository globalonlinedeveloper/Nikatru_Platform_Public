/** Replace the fenced region of `text` with `block`. Returns null when the file
 *  does not carry both markers, which is a FINDING and never a silent skip. */
export function spliceBlock(text, block) {
  const start = text.indexOf(MARK_START);
  if (start === -1) return null;
  const end = text.indexOf(MARK_END, start);
  if (end === -1) return null;
  return `${text.slice(0, start + MARK_START.length)}\n\n${block}\n\n${text.slice(end)}`;
}

