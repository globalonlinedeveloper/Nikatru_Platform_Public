  p(`<p class="meta">Declaration last re-read against the code: ${esc(doc.asOf)} &nbsp;·&nbsp; Itemised from <code>apps/${esc(appId)}/privacy.yaml</code> &nbsp;·&nbsp; The policy you agree to is the <a href="${esc(portfolioPolicyPath)}">Nikatru Privacy Policy</a>.</p>`);
